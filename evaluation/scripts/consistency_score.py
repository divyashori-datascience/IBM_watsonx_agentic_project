"""
Consistency Score
Checks if a persona gives consistent answers when asked the same question 3 times.
For each question: compares 3 answers → scores consistency → averages across all questions.
0.0 = very inconsistent, 1.0 = perfectly consistent.
"""

import sys
from pathlib import Path
from evaluation_utils import load_env, load_response
import os
import requests

_iam_token_cache = None

def get_iam_token() -> str:
    global _iam_token_cache
    if _iam_token_cache:
        return _iam_token_cache
    resp = requests.post(
        "https://iam.cloud.ibm.com/identity/token",
        headers={"Content-Type": "application/x-www-form-urlencoded"},
        data={
            "grant_type": "urn:ibm:params:oauth:grant-type:apikey",
            "apikey": os.environ["WATSONX_API_KEY"],
        },
        timeout=30,
    )
    resp.raise_for_status()
    _iam_token_cache = resp.json()["access_token"]
    return _iam_token_cache

def call_llm(prompt: str) -> str:
    token = get_iam_token()
    url = os.environ["WATSONX_URL"].rstrip("/")
    project_id = os.environ["WATSONX_PROJECT_ID"]
    model_id = os.environ.get("WATSONX_MODEL_ID", "meta-llama/llama-3-3-70b-instruct")
    payload = {
        "model_id": model_id,
        "project_id": project_id,
        "input": prompt,
        "parameters": {
            "max_new_tokens": 50,
            "temperature": 0.2,
        },
    }
    resp = requests.post(
        f"{url}/ml/v1/text/generation?version=2023-05-29",
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
        json=payload,
        timeout=60,
    )
    resp.raise_for_status()
    raw = resp.json()["results"][0]["generated_text"].strip()
    if "[/ANS]" in raw:
        raw = raw.split("[/ANS]")[0]
    elif "</s>" in raw:
        raw = raw.split("</s>")[0]
    return raw.strip()

def build_consistency_prompt(question: str, answers: list) -> str:
    # Build a prompt that shows the same question with 3 different answers
    # LLM will judge if the answers are consistent with each other
    return f"""You are evaluating whether a synthetic persona gives consistent answers to the same question.

QUESTION: {question}

ANSWER 1: {answers[0]}

ANSWER 2: {answers[1]}

ANSWER 3: {answers[2]}

Do these 3 answers express the same opinion, fee tolerance, and preferences?

Reply with ONLY a number between 0.0 and 1.0 where:
1.0 = all 3 answers are perfectly consistent
0.5 = some differences but same general direction
0.0 = answers clearly contradict each other

Reply with ONLY the number, nothing else."""


def score_consistency(response_file: Path) -> dict:
    # Load the persona response JSON that was generated by run_survey.py
    data = load_response(response_file)
    persona = data["persona"]
    results = data["results"]

    question_scores = []

    for item in results:
        q_id = item["question_id"]
        question = item["question"]

        # Get the 3 answers recorded for this question
        # These were saved by run_survey.py when it ran each question 3 times
        answers = item.get("answers", [])

        # Skip questions that don't have 3 answers
        # This can happen if the file was generated before the 3-run update
        if len(answers) < 3:
            print(f"  ⚠ {q_id}: only {len(answers)} answer(s), skipping")
            continue

        print(f"  {q_id}...")

        # Build the comparison prompt and call LLM
        prompt = build_consistency_prompt(question, answers)
        raw = call_llm(prompt)

        try:
            import re
            numbers = re.findall(r'\d+\.?\d*', raw)
            if numbers:
                score = float(numbers[0])
                score = max(0.0, min(1.0, score))
                print(f"    → {score}")
                question_scores.append({"question_id": q_id, "score": score})
            else:
                print(f"    Could not parse: {raw}")
        except:
            print(f"    Could not parse: {raw}")

    # Average all question scores to get the overall consistency score
    avg = round(
        sum(s["score"] for s in question_scores) / len(question_scores), 3
    ) if question_scores else 0.0

    return {
        "persona":            persona,
        "consistency_score":  avg,          # overall average across all questions
        "question_scores":    question_scores,  # per-question breakdown
        "file":               str(response_file),
    }


if __name__ == "__main__":
    load_env()
    file = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if not file:
        print("Usage: python consistency_score.py <response_file.json>")
        sys.exit(1)

    result = score_consistency(file)
    print(f"\nConsistency Score for {result['persona']}: {result['consistency_score']}")
    print(f"Per question: {result['question_scores']}")